#!/usr/bin/env python3
"""Compile immutable runtime path preparation for EVERY track.

The reference C implementation supplies fixed-point frames and route metadata.
No world-name allowlist, camera schedule, or silently unbaked track is used.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def emit(data, budget):
    if data['version'] != 2 or not data['tracks']:
        raise ValueError('invalid path package version or empty track catalog')
    lines = ['/* Generated by bake_path_runtime.py. Include path_runtime.h first. */']
    shared, rows, resident, report = {}, [], 0, []
    frames = {}
    for track in data['tracks']:
        ids=[]
        for row in track['frames']:
            key=tuple(row)
            if key not in frames: frames[key]=len(frames)
            ids.append(frames[key])
        track['frames']=ids
    lines.append('static const int16_t path_frame_rows[][6] = {')
    lines.extend('    {'+','.join(map(str,row))+'},' for row in frames)
    lines.append('};')
    resident+=len(frames)*12
    for track in data['tracks']:
        refs = []
        before = resident
        for field, ctype, width, columns in (
                ('frames', 'uint16_t', 2, 0), ('branches', 'int8_t', 1, 0),
                ('flags', 'uint8_t', 1, 0), ('clear', 'uint8_t', 1, 0),
                ('taper', 'uint8_t', 1, 0)):
            values = track[field]
            expected = track['segments'] if field in ('frames', 'taper') else track['bands']
            if len(values) != expected or (columns and any(len(row) != columns for row in values)):
                raise ValueError(f'{track["id"]}: {field} has invalid coverage')
            key = (ctype, columns, json.dumps(values, separators=(',', ':')))
            if key not in shared:
                name = f'path_baked_{len(shared)}'
                shared[key] = name
                suffix = f'[{columns}]' if columns else ''
                lines.append(f'static const {ctype} {name}[]{suffix} = {{')
                if columns:
                    lines += ['    {' + ','.join(map(str, row)) + '},' for row in values]
                else:
                    lines += ['    ' + ','.join(map(str, values[j:j+32])) + ',' for j in range(0, len(values), 32)]
                lines.append('};')
                resident += len(values) * width * (columns or 1)
            refs.append(shared[key])
        rows.append('    {' + ','.join(refs + [str(track['bands']), str(track['segments'])]) + '},')
        report.append(dict(track=track['id'], bands=track['bands'], segments=track['segments'],
                           preparation='compiled',
                           unique_bytes=resident-before))
    resident += len(rows) * 24  # Five PS1 pointers and two uint16 values.
    if resident > budget:
        raise ValueError(f'path package uses {resident} bytes, budget is {budget}')
    lines += ['static const PathRuntime path_runtime[] = {', *rows, '};',
              f'#define PATH_RUNTIME_COUNT {len(rows)}',
              'typedef char path_catalog_coverage[(PATH_RUNTIME_COUNT == TRACK_TABLE_COUNT) ? 1 : -1];', '']
    return '\n'.join(lines), dict(version=2, resident_bytes=resident, budget_bytes=budget,
        tracks=report, shared_arrays=len(shared), frame_rows=len(frames))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--header', type=Path, required=True)
    ap.add_argument('--report', type=Path, required=True)
    ap.add_argument('--cc', default=os.environ.get('HOST_CC', 'cc'))
    ap.add_argument('--budget', type=int, default=320000)
    args = ap.parse_args()
    with tempfile.TemporaryDirectory(prefix='runner-path-bake-') as temp:
        compiler = Path(temp)/'compile-path'
        subprocess.run([args.cc, '-std=gnu99', '-O2', '-DRUNNER_PREVIEW',
            '-I', str(ROOT/'src'), str(ROOT/'tools/compile_path_runtime.c'), '-o', str(compiler)], check=True)
        data = json.loads(subprocess.check_output([str(compiler)]))
    header, report = emit(data, args.budget)
    sources = [Path(__file__), ROOT/'tools/compile_path_runtime.c', ROOT/'src/path.c',
               ROOT/'src/path.h', ROOT/'src/path_runtime.h', ROOT/'src/track_data.h',
               ROOT/'src/world.h', ROOT/'src/course.h']
    report['source_sha256'] = hashlib.sha256(b''.join(p.read_bytes() for p in sources)).hexdigest()
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header)
    args.report.write_text(json.dumps(report, indent=2)+'\n')
    print(f'compiled paths: {len(data["tracks"])} tracks, {report["resident_bytes"]} resident bytes')


if __name__ == '__main__':
    main()
