#!/usr/bin/env python3
"""Synthesize the menu sounds and encode them as SPU ADPCM.

Each sound is a few short tones written here, so there are no audio files to
keep beside the build. The output is one C header with a block of ADPCM data
per sound, ready to upload to SPU RAM.
"""

import math
import sys
from pathlib import Path

RATE = 22050
F0 = (0, 60, 115, 98, 122)
F1 = (0, 0, -52, -55, -60)


def tone(freq, length, volume=0.5, decay=6.0, sweep_to=None, harmonics=(1.0, 0.0, 0.3, 0.0, 0.12)):
    n = int(RATE * length)
    out = []
    phase = 0.0
    for i in range(n):
        t = i / n
        f = freq if sweep_to is None else freq + (sweep_to - freq) * t
        phase += 2 * math.pi * f / RATE
        s = 0.0
        for k, amp in enumerate(harmonics, 1):
            if amp:
                s += amp * math.sin(phase * k)
        attack = min(1.0, i / (RATE * 0.003))
        env = attack * math.exp(-decay * t)
        out.append(s * env * volume)
    return out


def silence(length):
    return [0.0] * int(RATE * length)


def mix(*parts):
    out = []
    for part in parts:
        out += part
    return out


def overlay(a, b, at=0.0):
    start = int(RATE * at)
    out = list(a) + [0.0] * max(0, start + len(b) - len(a))
    for i, v in enumerate(b):
        out[start + i] += v
    return out


SOUNDS = {
    "MOVE": lambda: tone(1320, 0.045, 0.40, decay=5.0),
    "SELECT": lambda: mix(tone(880, 0.055, 0.45, decay=3.0), tone(1320, 0.11, 0.45, decay=4.0)),
    "BACK": lambda: mix(tone(740, 0.055, 0.42, decay=3.0), tone(494, 0.10, 0.42, decay=4.0)),
    "START": lambda: overlay(
        tone(440, 0.30, 0.38, decay=2.5, sweep_to=1760),
        mix(silence(0.14), tone(1760, 0.08, 0.30, decay=3.0), tone(2217, 0.08, 0.30, decay=3.0),
            tone(2637, 0.22, 0.30, decay=4.0))),
    "PAUSE": lambda: mix(tone(988, 0.06, 0.42, decay=3.0), tone(740, 0.06, 0.42, decay=3.0),
                         tone(988, 0.12, 0.42, decay=4.0)),
}


def to_pcm(samples):
    peak = max(1e-9, max(abs(v) for v in samples))
    scale = min(1.0, 0.95 / peak)
    return [max(-32768, min(32767, int(round(v * scale * 32767)))) for v in samples]


def encode_block(block, s1, s2):
    best = None
    for f in range(5):
        for shift in range(13):
            h1, h2 = s1, s2
            err = 0
            nibbles = []
            for s in block:
                pred = (h1 * F0[f] + h2 * F1[f] + 32) >> 6
                want = s - pred
                n = int(round(want * (1 << shift) / 4096))
                n = max(-8, min(7, n))
                out = ((n << 12) >> shift) + pred
                out = max(-32768, min(32767, out))
                err += (s - out) ** 2
                nibbles.append(n & 15)
                h2, h1 = h1, out
            if best is None or err < best[0]:
                best = (err, f, shift, nibbles, h1, h2)
    _err, f, shift, nibbles, h1, h2 = best
    return f, shift, nibbles, h1, h2


def encode(pcm):
    pcm = pcm + [0] * ((-len(pcm)) % 28)
    blocks = [pcm[i:i + 28] for i in range(0, len(pcm), 28)]
    blocks.append([0] * 28)
    data = bytearray()
    s1 = s2 = 0
    for i, block in enumerate(blocks):
        f, shift, nibbles, s1, s2 = encode_block(block, s1, s2)
        flags = 0x04 if i == 0 else 0
        if i == len(blocks) - 1:
            flags = 0x01
        data.append(shift | (f << 4))
        data.append(flags)
        for j in range(0, 28, 2):
            data.append(nibbles[j] | (nibbles[j + 1] << 4))
    # SPU DMA moves 64-byte blocks. The padding sits after the end flag and never plays.
    while len(data) % 64:
        data += bytes(16)
    return data


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: make_sounds.py OUTPUT_HEADER")
    names = list(SOUNDS)
    lines = [
        "#ifndef SOUND_BANK_H",
        "#define SOUND_BANK_H",
        "/* Generated by tools/make_sounds.py. SPU ADPCM, mono. */",
        f"#define SND_RATE {RATE}",
        f"#define SND_COUNT {len(names)}",
    ]
    blobs = []
    for n, name in enumerate(names):
        lines.append(f"#define SND_{name} {n}")
        blobs.append(encode(to_pcm(SOUNDS[name]())))
    offsets = []
    blob = bytearray()
    for data in blobs:
        offsets.append(len(blob))
        blob += data
    lines.append("static const uint32_t snd_off[SND_COUNT] = { " + ", ".join(map(str, offsets)) + " };")
    lines.append("static const uint32_t snd_len[SND_COUNT] = { " + ", ".join(str(len(b)) for b in blobs) + " };")
    lines.append(f"static const uint8_t snd_data[{len(blob)}] __attribute__((aligned(4))) = {{")
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
    lines.append("};")
    lines.append("#endif")
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
    print(f"sounds: {', '.join(names)} ({len(blob)} bytes)")


if __name__ == "__main__":
    main()
