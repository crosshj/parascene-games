#!/usr/bin/env python3
"""Bake opaque window facades and energy-filtered distance tiles (4-bit PS1)."""
import json
import random
import sys
from pathlib import Path

# Each hue has eight coverage levels, including opaque dark masonry.
BASE = (12, 16, 28)
HUES = ((255, 192, 88), (88, 216, 248))
COVER = (0, .06, .14, .25, .4, .6, .8, 1)
PALETTE = [tuple(round((a + (b-a)*t)/8)*8 for a,b in zip(BASE,h))
           for h in HUES for t in COVER]
PALETTE = [tuple(min(248,c) for c in p) for p in PALETTE]

def bake():
    atlas = [[0]*256 for _ in range(64)]
    tiles, means = [], []
    for variant in range(2):
        rng = random.Random(0x5EEDC17 + variant * 104729)
        occupied = [[rng.random() < 0.30 for _ in range(8)] for _ in range(8)]
        src = [[BASE for _ in range(64)] for _ in range(64)]
        for y in range(64):
            for x in range(64):
                col, row = x//8, y//8
                lit = occupied[row][col]
                if lit and 2 <= x%8 <= 4 and 2 <= y%8 <= 4:
                    src[y][x] = HUES[variant]
        means.append([sum(p[c] for row in src for p in row)//4096 for c in range(3)])
        for lod, (size, origin) in enumerate(((64,variant*64), (32,128+variant*32),
                                             (16,192+variant*16), (8,224+variant*8))):
            scale = 64//size
            for y in range(size):
                for x in range(size):
                    avg = [sum(src[yy][xx][c] for yy in range(y*scale,(y+1)*scale)
                               for xx in range(x*scale,(x+1)*scale))/(scale*scale) for c in range(3)]
                    idx = min(range(variant*8,variant*8+8),
                              key=lambda i: sum((PALETTE[i][c]-avg[c])**2 for c in range(3)))
                    atlas[y][origin+x] = idx
            tiles.append(dict(variant=variant,lod=lod,u=origin,v=128,size=size))
    packed = [row[x] | row[x+1]<<4 for row in atlas for x in range(0,256,2)]
    return packed, tiles, means

def straight_runs(segments):
    """End of each provably constant-frame/width run, in course units."""
    ends=[s['s']+256 for s in segments]
    for i in range(len(segments)-2,-1,-1):
        a,b=segments[i:i+2]
        keys=('yaw','pitch','roll','edge','edge1','right','right1','up','fwd')
        same=all(a[k]==b[k] for k in keys) and a['edge']==a['edge1']
        same &= a['chain']==b['chain']=='main' and a['next']==i+1
        same &= all(abs(a['p1'][j]-b['p'][j])<1e-5 and
                    abs((a['p1'][j]-a['p'][j])-(b['p1'][j]-b['p'][j]))<1e-5 for j in range(3))
        # Stop at b's start when its endpoint is turning/banking: the next
        # iteration already bounds the safe run through that endpoint.
        if same: ends[i]=ends[i+1]
    return ends

def main():
    packed, tiles, means = bake()
    out = Path(sys.argv[1])
    lines = ['/* Generated by bake_vesper.py. Opaque facade + box-filtered LODs. */', '#pragma once']
    for name, values, typ in [('vesper_pixels', packed, 'uint8_t'),
                              ('vesper_palette', [(r>>3)|((g>>3)<<5)|((b>>3)<<10) for r,g,b in PALETTE], 'uint16_t')]:
        lines.append(f'static const {typ} {name}[] __attribute__((aligned(4))) = {{')
        lines += [','.join(str(v) for v in values[i:i+32])+',' for i in range(0,len(values),32)]
        lines.append('};')
    lines.append('static const uint8_t vesper_mean[2][3] = {' + ','.join('{'+','.join(map(str,m))+'}' for m in means) + '};')
    tracks=json.loads((Path(__file__).resolve().parent/'trackview/baked.json').read_text())['tracks']
    track=next(t for t in tracks if t['id']=='vesper.hook')
    runs=straight_runs(track['segments'])
    lines.append('static const uint32_t vesper_city_runs[] = {'+','.join(map(str,runs))+'};')
    lines.append('#define VESPER_CITY_RUN_COUNT '+str(len(runs)))
    out.write_text('\n'.join(lines)+'\n')
    out.with_suffix('.json').write_text(json.dumps(dict(texture_bytes=len(packed),palette_bytes=32,
        vram=[960,128,64,64],clut=[0,483,16,1],tiles=tiles,mean=means),indent=2)+'\n')
    print('Vesper: 8,192 texture bytes + 32 palette bytes; 2 facades, 4 filtered detail levels')

if __name__ == '__main__':
    main()
